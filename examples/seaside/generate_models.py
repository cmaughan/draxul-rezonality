# Lighthouse and headland

TOWER, GALLERY, LANTERN, ROOF, LH_WINDOW, DOOR, HOUSE, HOUSE_ROOF, RAIL, ROCK = (
    0.05, 0.15, 0.25, 0.35, 0.45, 0.55, 0.65, 0.75, 0.85, 0.95)


def shoreline_radius(a):
    """Island shoreline radius. Mirrored in night.glsl."""
    return 17.0 + 3.0 * math.sin(3.0 * a + 1.0) + 2.0 * math.sin(5.0 * a + 2.0) + 1.2 * math.sin(9.0 * a + 0.5)


def headland_height(x, z):
    r = math.hypot(x, z)
    a = math.atan2(z, x)
    inside = shoreline_radius(a) - r  # metres inland of the shoreline
    # Steep cliff band, then a rounded crown that peaks at the lighthouse.
    cliff = 1.0 / (1.0 + math.exp(-inside * 1.3))
    crown = max(0.0, 1.0 - (r / 16.0) ** 2)
    h = -2.5 + 9.0 * cliff + 2.2 * crown
    rough = (0.55 * math.sin(x * 0.9 + 1.3) * math.sin(z * 0.7 + 0.4)
             + 0.3 * math.sin(x * 2.1 + z * 1.3) + 0.22 * math.sin(z * 2.7 - x * 0.6 + 2.0)
             + 0.12 * math.sin(x * 4.3 + 0.7) * math.sin(z * 3.9 + 1.1)
             + 0.6 * math.sin(a * 13.0 + 0.4) * math.sin(r * 0.8))
    # Ledges: soft terraces in the cliff band, like stacked basalt.
    cliff_band = cliff * (1.0 - cliff) * 4.0
    h += rough * (0.5 + 1.1 * cliff_band)
    h += 0.6 * math.sin(h * 2.2) * cliff_band
    # Flatten a pad for the lighthouse and cottage.
    pad = math.exp(-((x * x + z * z) / 30.0))
    h = h * (1.0 - pad) + 8.6 * pad
    return h


def headland():
    mesh = Mesh("headland")
    rings, segments = 70, 200
    r_max = 30.0
    grid = []
    for i in range(rings + 1):
        r = r_max * (i / rings) ** 1.15
        row = []
        for j in range(segments):
            a = 2.0 * math.pi * j / segments
            x, z = r * math.cos(a), r * math.sin(a)
            y = headland_height(x, z)
            row.append((x, y, z))
        grid.append(row)

    def normal_at(x, z):
        e = 0.08
        hx = headland_height(x + e, z) - headland_height(x - e, z)
        hz = headland_height(x, z + e) - headland_height(x, z - e)
        return norm((-hx, 2.0 * e, -hz))

    ids = []
    for i, row in enumerate(grid):
        ids.append([mesh.vert(p, (ROCK, p[1]), normal_at(p[0], p[2])) for p in row])
    for i in range(rings):
        for j in range(segments):
            jn = (j + 1) % segments
            mesh.quad(ids[i][j], ids[i + 1][j], ids[i + 1][jn], ids[i][jn])

    # Surf-washed boulders scattered along the shoreline.
    rng = random.Random(7)
    for b in range(26):
        a = rng.uniform(0.0, 2.0 * math.pi)
        r = shoreline_radius(a) + rng.uniform(-0.5, 2.8)
        cx, cz = r * math.cos(a), r * math.sin(a)
        size = rng.uniform(0.6, 1.8)
        boulder(mesh, (cx, -0.4 + size * 0.3, cz), size, rng)
    mesh.write("headland.obj")


def boulder(mesh, center, size, rng):
    lat, lon = 7, 10
    bumps = [(rng.uniform(-1, 1), rng.uniform(-1, 1), rng.uniform(-1, 1)) for _ in range(4)]
    rows = []
    for i in range(lat + 1):
        th = math.pi * i / lat
        row = []
        for j in range(lon):
            ph = 2.0 * math.pi * j / lon
            d = (math.sin(th) * math.cos(ph), math.cos(th), math.sin(th) * math.sin(ph))
            r = size * (1.0 + 0.18 * sum(math.sin(3.0 * (d[0] * b[0] + d[1] * b[1] + d[2] * b[2]) + k)
                                          for k, b in enumerate(bumps)) / 2.0)
            p = (center[0] + d[0] * r * 1.2, center[1] + d[1] * r * 0.75, center[2] + d[2] * r)
            row.append(mesh.vert(p, (ROCK, p[1]), d))
        rows.append(row)
    for i in range(lat):
        for j in range(lon):
            jn = (j + 1) % lon
            mesh.quad(rows[i][j], rows[i + 1][j], rows[i + 1][jn], rows[i][jn])


def lighthouse():
    mesh = Mesh("lighthouse")
    base_y = 8.4
    tower_h = 13.0
    r_base, r_top = 2.0, 1.35
    profile = [(r_base + 0.25, base_y - 0.6), (r_base + 0.25, base_y + 0.4), (r_base, base_y + 0.45)]
    for i in range(1, 21):
        t = i / 20.0
        profile.append((r_base + (r_top - r_base) * t ** 0.9, base_y + 0.45 + tower_h * t))
    lathe(mesh, profile, 40, TOWER)
    top = base_y + 0.45 + tower_h

    # Gallery deck with corbels, plus a railing.
    lathe(mesh, [(r_top - 0.05, top - 0.5), (r_top + 0.75, top - 0.05), (r_top + 0.85, top),
                 (r_top + 0.85, top + 0.18), (0.0, top + 0.18)], 40, GALLERY)
    for ry in (0.55, 1.05):
        lathe(mesh, [(r_top + 0.8, top + ry), (r_top + 0.84, top + ry + 0.025),
                     (r_top + 0.8, top + ry + 0.05), (r_top + 0.76, top + ry + 0.025),
                     (r_top + 0.8, top + ry)], 40, RAIL)
    for k in range(20):
        a = 2.0 * math.pi * k / 20
        x, z = (r_top + 0.8) * math.cos(a), (r_top + 0.8) * math.sin(a)
        tube(mesh, [(x, top + 0.18, z), (x, top + 1.08, z)], [0.022, 0.022], 4, RAIL, cap=False)

    # Lantern room: glazed drum with mullions, a domed roof, vent ball and rod.
    lr = 1.05
    lathe(mesh, [(lr + 0.06, top + 0.18), (lr + 0.06, top + 0.7), (lr, top + 0.72)], 32, GALLERY)
    lathe(mesh, [(lr, top + 0.72), (lr, top + 2.3)], 32, LANTERN)
    for k in range(10):
        a = 2.0 * math.pi * (k + 0.5) / 10
        x, z = (lr + 0.02) * math.cos(a), (lr + 0.02) * math.sin(a)
        tube(mesh, [(x, top + 0.7, z), (x, top + 2.32, z)], [0.035, 0.035], 4, ROOF, cap=False)
    dome = [(lr + 0.22, top + 2.3), (lr + 0.22, top + 2.4)]
    for i in range(1, 11):
        a = (math.pi * 0.5) * i / 10
        dome.append(((lr + 0.15) * math.cos(a), top + 2.4 + 1.0 * math.sin(a)))
    lathe(mesh, dome, 32, ROOF)
    ball = []
    for i in range(9):
        a = -math.pi * 0.5 + math.pi * i / 8
        ball.append((0.22 * math.cos(a) + 1e-3, top + 3.62 + 0.22 * math.sin(a)))
    lathe(mesh, ball, 16, ROOF)
    tube(mesh, [(0.0, top + 3.8, 0.0), (0.0, top + 4.7, 0.0)], [0.025, 0.012], 5, ROOF)

    # Tower door and a column of small windows facing the camera side (-Z/+X).
    door_a = math.radians(-60.0)
    dx, dz = math.cos(door_a), math.sin(door_a)
    for y in (base_y + 4.0, base_y + 7.6, base_y + 11.0):
        r = r_base + (r_top - r_base) * ((y - base_y) / tower_h) + 0.02
        c = (r * dx, y, r * dz)
        tx, tz = -dz, dx
        quad_on_wall(mesh, c, (tx, 0.0, tz), (dx, 0.0, dz), 0.32, 0.55, LH_WINDOW)
    c = ((r_base + 0.27) * dx, base_y + 0.5, (r_base + 0.27) * dz)
    quad_on_wall(mesh, c, (-dz, 0.0, dx), (dx, 0.0, dz), 0.55, 1.0, DOOR, bottom=True)

    # Keeper's cottage with a gabled roof, chimney and lit windows.
    hx, hz = 5.2, 2.6
    lo = (hx - 2.6, base_y - 0.8, hz - 1.7)
    hi = (hx + 2.6, base_y + 2.4, hz + 1.7)
    box(mesh, lo, hi, HOUSE)
    ridge = base_y + 4.0
    eave = hi[1]
    ov = 0.3
    for sz in (-1.0, 1.0):
        zc = hz + sz * (1.7 + ov)
        n = (0.0, 1.6, sz * 1.7)
        a = mesh.vert((lo[0] - ov, eave - 0.2, zc), (HOUSE_ROOF, 0.0), n)
        b = mesh.vert((hi[0] + ov, eave - 0.2, zc), (HOUSE_ROOF, 0.0), n)
        c = mesh.vert((hi[0] + ov, ridge, hz), (HOUSE_ROOF, 1.0), n)
        d = mesh.vert((lo[0] - ov, ridge, hz), (HOUSE_ROOF, 1.0), n)
        mesh.quad(a, b, c, d)
    for sx in (lo[0], hi[0]):
        nx = -1.0 if sx == lo[0] else 1.0
        a = mesh.vert((sx, eave, hz - 1.7), (HOUSE, 1.0), (nx, 0.0, 0.0))
        b = mesh.vert((sx, eave, hz + 1.7), (HOUSE, 1.0), (nx, 0.0, 0.0))
        c = mesh.vert((sx, ridge - 0.15, hz), (HOUSE, 1.0), (nx, 0.0, 0.0))
        mesh.tri(a, b, c)
    box(mesh, (hx + 1.4, ridge - 1.2, hz + 0.3), (hx + 1.9, ridge + 0.7, hz + 0.8), HOUSE)
    for wx in (hx - 1.5, hx, hx + 1.5):
        box(mesh, (wx - 0.32, base_y + 0.55, lo[2] - 0.03), (wx + 0.32, base_y + 1.55, lo[2] + 0.01), LH_WINDOW)
    box(mesh, (lo[0] - 0.03, base_y + 0.55, hz - 0.4), (lo[0] + 0.01, base_y + 1.55, hz + 0.4), LH_WINDOW)

    mesh.write("lighthouse.obj")


def quad_on_wall(mesh, c, tangent, normal, w, h, part, bottom=False):
    y0 = c[1] if bottom else c[1] - h * 0.5
    pts = []
    for su, sv in ((-1, 0), (1, 0), (1, 1), (-1, 1)):
        p = (c[0] + tangent[0] * w * 0.5 * su, y0 + h * sv, c[2] + tangent[2] * w * 0.5 * su)
        pts.append(mesh.vert(p, (part, float(sv)), normal))
    mesh.quad(pts[0], pts[3], pts[2], pts[1])


