# Fish school

BODY, FIN = 0.2, 0.6


def fish_body(mesh, fid, species, rng):
    """One fish around the origin, nose toward -Z, length ~1.

    color = (id, along-body 0..1 from nose to tail, species).
    """
    stations = 10
    sides = 8
    if species == 0.0:   # sardine: slender, silver
        width, height = 0.085, 0.13
    else:                # garibaldi: deep, rounded body
        width, height = 0.12, 0.3
    rings = []
    for i in range(stations + 1):
        t = i / stations
        z = -0.5 + 0.82 * t
        env = math.sin(min(t * 1.05, 1.0) * math.pi) ** (0.55 if t < 0.5 else 0.9)
        env = max(env, 0.04)
        ring = []
        for j in range(sides):
            a = 2.0 * math.pi * j / sides
            n = (math.cos(a) / width, math.sin(a) / height, 0.0)
            p = (math.cos(a) * width * env, math.sin(a) * height * env, z)
            ring.append(mesh.vert(p, (BODY, t), n, (fid, t * 0.82, species)))
        rings.append(ring)
    for i in range(stations):
        for j in range(sides):
            k = (j + 1) % sides
            mesh.quad(rings[i][j], rings[i + 1][j], rings[i + 1][k], rings[i][k])
    nose = mesh.vert((0.0, 0.0, -0.53), (BODY, 0.0), (0.0, 0.0, -1.0), (fid, 0.0, species))
    for j in range(sides):
        mesh.tri(nose, rings[0][(j + 1) % sides], rings[0][j])
    # Forked tail fin.
    zt = 0.32
    tail_h = height * (1.1 if species == 0.0 else 0.8)
    a = mesh.vert((0.0, 0.0, zt - 0.04), (FIN, 0.0), (1.0, 0.0, 0.0), (fid, 0.82, species))
    b = mesh.vert((0.0, tail_h, zt + 0.2), (FIN, 1.0), (1.0, 0.0, 0.0), (fid, 1.0, species))
    c = mesh.vert((0.0, 0.02, zt + 0.1), (FIN, 0.6), (1.0, 0.0, 0.0), (fid, 0.95, species))
    d = mesh.vert((0.0, -tail_h, zt + 0.2), (FIN, 1.0), (1.0, 0.0, 0.0), (fid, 1.0, species))
    mesh.tri(a, b, c)
    mesh.tri(a, c, d)
    # Dorsal fin.
    e = mesh.vert((0.0, height * 0.85, -0.12), (FIN, 0.0), (1.0, 0.0, 0.0), (fid, 0.38, species))
    f = mesh.vert((0.0, height * 1.35, 0.0), (FIN, 1.0), (1.0, 0.0, 0.0), (fid, 0.5, species))
    g = mesh.vert((0.0, height * 0.7, 0.12), (FIN, 0.3), (1.0, 0.0, 0.0), (fid, 0.62, species))
    mesh.tri(e, f, g)


def fish():
    mesh = Mesh("fish_school")
    rng = random.Random(5)
    sardines, garibaldi = 220, 7
    total = sardines + garibaldi
    for i in range(total):
        species = 0.0 if i < sardines else 1.0
        fish_body(mesh, (i + 0.5) / total, species, rng)
    mesh.write("fish.obj")


