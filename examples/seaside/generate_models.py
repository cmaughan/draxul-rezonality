# Sailboat

HULL, DECK, CABIN, SPAR, MAINSAIL, JIB, PENNANT, WINDOW, STAY = (
    0.05, 0.15, 0.25, 0.35, 0.5, 0.6, 0.7, 0.8, 0.9)


def sailboat():
    mesh = Mesh("sailboat")
    length, beam = 8.4, 2.7
    bow_z, stern_z = -length * 0.5, length * 0.5
    stations = 34
    section_pts = 18

    def profile(z):
        t = (z - bow_z) / length  # 0 at bow, 1 at stern
        # Half-beam: fine entry, full aft, transom stern.
        w = beam * 0.5 * (math.sin(min(t * 1.25, 1.0) * math.pi * 0.5) ** 0.75)
        w *= 1.0 - 0.18 * max(t - 0.75, 0.0) / 0.25
        sheer = 0.62 + 0.38 * (1.0 - t) ** 3 + 0.05 * t
        depth = 0.75 * (0.35 + 0.65 * math.sin(min(t * 1.1, 1.0) * math.pi) ** 0.5) * (1.0 - 0.45 * t)
        return max(w, 0.015), sheer, max(depth, 0.08)

    rings = []
    for i in range(stations + 1):
        z = bow_z + length * i / stations
        w, sheer, depth = profile(z)
        ring = []
        for j in range(section_pts + 1):
            th = math.pi * j / section_pts  # 0 = starboard gunwale, pi = port gunwale
            c, s = math.cos(th), math.sin(th)
            x = w * math.copysign(abs(c) ** 0.8, c)
            y = sheer - (sheer + depth) * (s ** 0.7)
            n = (math.copysign(abs(c) ** 1.2, c) / w, -(s ** 1.3) / (sheer + depth) * 0.8, 0.0)
            ring.append((x, y, z, n))
        rings.append(ring)

    hull_ids = []
    for i, ring in enumerate(rings):
        hull_ids.append([mesh.vert(p[:3], (HULL, p[1]), p[3]) for p in ring])
    for i in range(stations):
        for j in range(section_pts):
            mesh.quad(hull_ids[i][j], hull_ids[i + 1][j], hull_ids[i + 1][j + 1], hull_ids[i][j + 1])

    # Transom.
    stern = rings[-1]
    mid = mesh.vert((0.0, stern[0][1] * 0.3, stern_z), (HULL, 0.3), (0.0, 0.0, 1.0))
    ids = [mesh.vert(p[:3], (HULL, p[1]), (0.0, 0.0, 1.0)) for p in stern]
    for j in range(section_pts):
        mesh.tri(mid, ids[j], ids[j + 1])

    # Cambered teak deck between the gunwales.
    for i in range(stations):
        a0, a1 = rings[i][0], rings[i][-1]
        b0, b1 = rings[i + 1][0], rings[i + 1][-1]
        strip = []
        for ring_pts in ((a0, a1), (b0, b1)):
            row = []
            for k in range(5):
                u = k / 4.0
                p = lerp(ring_pts[0][:3], ring_pts[1][:3], u)
                width = abs(ring_pts[0][0]) + 1e-3
                camber = 0.06 * (1.0 - (2.0 * u - 1.0) ** 2) * min(width / 0.6, 1.0)
                row.append(mesh.vert((p[0], p[1] - 0.02 + camber, p[2]), (DECK, u), (0.0, 1.0, 0.0)))
            strip.append(row)
        for k in range(4):
            mesh.quad(strip[0][k], strip[0][k + 1], strip[1][k + 1], strip[1][k])

    # Toe rail along both gunwales.
    for side in (0, -1):
        path = [(r[side][0] * 0.98, r[side][1] + 0.04, r[side][2]) for r in rings]
        tube(mesh, path, [0.035] * len(path), 5, SPAR)

    deck_y = 0.66
    # Cabin trunk with a raked front and glowing ports.
    cabin_lo, cabin_hi = (-0.62, deck_y - 0.05, -0.9), (0.62, deck_y + 0.5, 1.6)
    box(mesh, cabin_lo, cabin_hi, CABIN)
    for z in (-0.4, 0.3, 1.0):
        for x in (0.625, -0.625):
            box(mesh, (x - 0.01, deck_y + 0.2, z - 0.18), (x + 0.01, deck_y + 0.36, z + 0.18), WINDOW)
    # Companionway hatch.
    box(mesh, (-0.35, deck_y + 0.5, 0.4), (0.35, deck_y + 0.58, 1.3), CABIN)
    # Cockpit coaming.
    box(mesh, (-0.85, deck_y - 0.02, 1.9), (0.85, deck_y + 0.22, 3.6), CABIN)

    # Spars. Mast steps through the cabin roof.
    mast_z = -1.15
    mast_top = 10.2
    tube(mesh, [(0.0, deck_y, mast_z), (0.0, mast_top, mast_z)], [0.075, 0.055], 10, SPAR)
    # Spreaders.
    tube(mesh, [(-0.85, 6.2, mast_z), (0.85, 6.2, mast_z)], [0.03, 0.03], 6, SPAR)
    # Boom, swung out to port on a broad reach.
    boom_angle = math.radians(24.0)
    boom_len = 4.2
    boom_y = deck_y + 1.15
    boom_end = (-math.sin(boom_angle) * boom_len, boom_y, mast_z + math.cos(boom_angle) * boom_len)
    tube(mesh, [(0.0, boom_y, mast_z), boom_end], [0.065, 0.05], 8, SPAR)

    # Mainsail: tack at the gooseneck, head at the masthead, clew at the boom end.
    tack = (0.0, boom_y + 0.05, mast_z + 0.06)
    head = (0.0, mast_top - 0.35, mast_z + 0.06)
    clew = (boom_end[0], boom_end[1] + 0.06, boom_end[2])
    sheet(mesh, tack, head, clew, 18, MAINSAIL, lambda u, v: (u, v, 0.0))

    # Jib: head below the masthead, tack at the stem, clew trimmed out to port.
    bow_top = (0.0, profile(bow_z + 0.05)[1] + 0.05, bow_z + 0.15)
    jib_head = (0.0, 8.5, mast_z - 0.12)
    jib_clew = (-1.25, deck_y + 0.75, mast_z + 1.45)
    sheet(mesh, bow_top, jib_head, jib_clew, 16, JIB, lambda u, v: (u, v, 1.0))

    # Standing rigging.
    stays = [
        [(0.0, mast_top - 0.1, mast_z), bow_top],
        [(0.0, mast_top - 0.1, mast_z), (0.0, 1.0, stern_z - 0.1)],
        [(0.0, 6.2, mast_z), (0.85, 6.2, mast_z), (beam * 0.48, deck_y + 0.05, mast_z + 0.2)],
        [(0.0, 6.2, mast_z), (-0.85, 6.2, mast_z), (-beam * 0.48, deck_y + 0.05, mast_z + 0.2)],
        [(0.85, 6.2, mast_z), (0.0, mast_top - 0.3, mast_z)],
        [(-0.85, 6.2, mast_z), (0.0, mast_top - 0.3, mast_z)],
    ]
    for path in stays:
        for p0, p1 in zip(path[:-1], path[1:]):
            tube(mesh, [p0, p1], [0.012, 0.012], 4, STAY, cap=False)
    # Mainsheet from the boom end down to the cockpit.
    tube(mesh, [boom_end, (-0.3, deck_y + 0.25, 2.9)], [0.012, 0.012], 4, STAY, cap=False)

    # Masthead pennant: a long thin triangle strip that flutters in the shader.
    segments = 12
    p_len = 1.1
    for i in range(segments):
        u0, u1 = i / segments, (i + 1) / segments
        h0, h1 = 0.14 * (1.0 - u0), 0.14 * (1.0 - u1)
        y = mast_top + 0.05
        a = mesh.vert((0.0, y, mast_z + u0 * p_len), (PENNANT, u0), (1.0, 0.0, 0.0), (u0, 0.0, 0.0))
        b = mesh.vert((0.0, y + h0, mast_z + u0 * p_len), (PENNANT, u0), (1.0, 0.0, 0.0), (u0, 1.0, 0.0))
        c = mesh.vert((0.0, y + h1 * 0.5 + (h0 - h1) * 0.5, mast_z + u1 * p_len), (PENNANT, u1), (1.0, 0.0, 0.0), (u1, 1.0, 0.0))
        d = mesh.vert((0.0, y + (h0 - h1) * 0.5, mast_z + u1 * p_len), (PENNANT, u1), (1.0, 0.0, 0.0), (u1, 0.0, 0.0))
        mesh.quad(a, d, c, b)

    mesh.write("sailboat.obj")


