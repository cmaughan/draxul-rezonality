# Kelp forest

STIPE, BLADE, BLADDER = 0.1, 0.5, 0.8


def kelp():
    mesh = Mesh("kelp")
    rng = random.Random(11)
    strands = []
    while len(strands) < 64:
        x = rng.uniform(-36.0, 36.0)
        z = rng.uniform(-62.0, 6.0)
        # Keep a clear swim lane in front of the camera.
        if abs(x - 1.0) < 3.5 + max(0.0, z + 20.0) * 0.12 and z > -24.0:
            continue
        if any((x - sx) ** 2 + (z - sz) ** 2 < 7.0 for sx, sz, _ in strands):
            continue
        strands.append((x, z, rng.uniform(14.0, 19.5)))

    for sid, (x, z, height) in enumerate(strands):
        phase = (sid * 0.618034) % 1.0
        segs = 28
        lean = (rng.uniform(-0.8, 0.8), rng.uniform(-0.8, 0.8))
        path = []
        for i in range(segs + 1):
            h = i / segs
            path.append((x + lean[0] * h * h * 2.0 + 0.3 * math.sin(h * 5.0 + sid),
                         -0.3 + height * h,
                         z + lean[1] * h * h * 2.0 + 0.3 * math.cos(h * 4.0 + sid)))
        # Stipe: encode height fraction in color.g per ring via a custom sweep.
        rings = []
        for i, p in enumerate(path):
            h = i / segs
            ring = []
            for j in range(5):
                a = 2.0 * math.pi * j / 5
                n = (math.cos(a), 0.0, math.sin(a))
                q = (p[0] + n[0] * 0.05, p[1], p[2] + n[2] * 0.05)
                ring.append(mesh.vert(q, (STIPE, h), n, (phase, h, 0.0)))
            rings.append(ring)
        for i in range(segs):
            for j in range(5):
                k = (j + 1) % 5
                mesh.quad(rings[i][j], rings[i][k], rings[i + 1][k], rings[i + 1][j])

        # Blades alternate up the stipe, each with a small gas bladder at its base.
        blade_count = int(height * 3.2)
        for b in range(blade_count):
            hb = 0.06 + 0.92 * (b + rng.uniform(0.0, 0.6)) / blade_count
            idx = hb * segs
            i0 = min(int(idx), segs - 1)
            base = lerp(path[i0], path[i0 + 1], idx - i0)
            ang = b * 2.4 + rng.uniform(-0.4, 0.4)
            out = (math.cos(ang), 0.0, math.sin(ang))
            blade_len = rng.uniform(1.3, 2.3) * (1.0 - 0.2 * hb)
            blade_w = rng.uniform(0.17, 0.27)
            droop = rng.uniform(0.25, 0.6)
            steps = 7
            side = (-out[2], 0.0, out[0])
            prev = None
            for s in range(steps + 1):
                u = s / steps
                center = add(add(base, scale(out, 0.12 + blade_len * u)), (0.0, (0.35 - droop * u) * u, 0.0))
                w = blade_w * math.sin(min(u * 1.15, 1.0) * math.pi) ** 0.6 + 0.01
                ruffle = 0.05 * math.sin(u * 19.0 + b)
                left = add(center, scale(side, w + ruffle))
                right = add(center, scale(side, -w + ruffle))
                n = norm(cross(side, (out[0], 0.6 - droop * u * 2.0, out[2])))
                c = (phase, hb, u)
                a = mesh.vert(left, (BLADE, u), n, c)
                d = mesh.vert(right, (BLADE, u), n, c)
                if prev:
                    mesh.quad(prev[0], prev[1], d, a)
                prev = (a, d)
            # Bladder: a tiny diamond.
            bc = add(base, scale(out, 0.09))
            r = 0.055
            pts = [add(bc, (0, r, 0)), add(bc, (0, -r, 0)), add(bc, scale(out, r)),
                   add(bc, scale(out, -r)), add(bc, scale(side, r)), add(bc, scale(side, -r))]
            ids = [mesh.vert(p, (BLADDER, 0.5), sub(p, bc), (phase, hb, 0.0)) for p in pts]
            top, bot, f, bk, l, rr = ids
            for e0, e1 in ((f, l), (l, bk), (bk, rr), (rr, f)):
                mesh.tri(top, e0, e1)
                mesh.tri(bot, e1, e0)

    mesh.write("kelp.obj")


