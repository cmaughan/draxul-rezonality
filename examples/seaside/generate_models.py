#!/usr/bin/env python3
"""Generate the meshes used by the SEASIDE panes.

Rezonality draws one model per pass, has no instancing and gives every model
an identity transform, so animation lives in the vertex shaders. Per-instance
and per-part data is baked into the spare vertex channels instead:

    uv.x      material part id (see the *_PART constants below)
    uv.y      a parameter along the part (height, length, ...)
    color.rgb per-instance data (id, along-body factor, species ...)

Outputs (written next to this script):

    ocean_grid.obj  camera-centred polar grid, displaced by Gerstner waves
                    (also the seabed in the kelp pane)
    sailboat.obj    sloop: hull, deck, cabin, mast, boom, sails, pennant, stays
    lighthouse.obj  banded tower, gallery, lantern, dome and keeper's cottage
    headland.obj    rocky promontory that carries the lighthouse
    kelp.obj        a forest of giant-kelp stipes with blades and bladders
    fish.obj        a school of sardines plus a few garibaldi

Forward is -Z and up is +Y throughout. Run:  python3 generate_models.py
"""

import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))


class Mesh:
    def __init__(self, name):
        self.name = name
        self.v, self.c, self.vt, self.vn, self.f = [], [], [], [], []

    def vert(self, p, uv=(0.0, 0.0), n=(0.0, 1.0, 0.0), c=(0.0, 0.0, 0.0)):
        self.v.append(p)
        self.c.append(c)
        self.vt.append(uv)
        length = math.sqrt(sum(x * x for x in n)) or 1.0
        self.vn.append(tuple(x / length for x in n))
        return len(self.v)  # OBJ indices are 1-based

    def tri(self, a, b, c):
        self.f.append((a, b, c))

    def quad(self, a, b, c, d):
        self.tri(a, b, c)
        self.tri(a, c, d)

    def write(self, filename, colors=True, normals=True, uvs=True):
        path = os.path.join(HERE, filename)
        with open(path, "w", newline="\n") as out:
            out.write("# %s, generated by generate_models.py\n" % self.name)
            out.write("o %s\n" % self.name)
            for p, c in zip(self.v, self.c):
                if colors:
                    out.write("v %.4f %.4f %.4f %.4f %.4f %.4f\n" % (p + c))
                else:
                    out.write("v %.4f %.4f %.4f\n" % p)
            if uvs:
                for t in self.vt:
                    out.write("vt %.4f %.4f\n" % t)
            if normals:
                for n in self.vn:
                    out.write("vn %.3f %.3f %.3f\n" % n)
            for a, b, c in self.f:
                if uvs and normals:
                    out.write("f %d/%d/%d %d/%d/%d %d/%d/%d\n" % (a, a, a, b, b, b, c, c, c))
                elif normals:
                    out.write("f %d//%d %d//%d %d//%d\n" % (a, a, b, b, c, c))
                else:
                    out.write("f %d %d %d\n" % (a, b, c))
        print("wrote %s: %d vertices, %d triangles" % (filename, len(self.v), len(self.f)))


def norm(v):
    length = math.sqrt(sum(x * x for x in v)) or 1.0
    return tuple(x / length for x in v)


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def scale(a, s):
    return tuple(x * s for x in a)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def lerp(a, b, t):
    return tuple(x + (y - x) * t for x, y in zip(a, b))


def tube(mesh, path, radii, sides, part, color=(0.0, 0.0, 0.0), cap=True, v_range=(0.0, 1.0)):
    """Sweep a circle along a polyline. radii: one radius per path point."""
    count = len(path)
    rings = []
    for i, p in enumerate(path):
        tangent = norm(sub(path[min(i + 1, count - 1)], path[max(i - 1, 0)]))
        ref = (0.0, 1.0, 0.0) if abs(tangent[1]) < 0.9 else (1.0, 0.0, 0.0)
        side = norm(cross(tangent, ref))
        up = cross(side, tangent)
        v = v_range[0] + (v_range[1] - v_range[0]) * i / (count - 1)
        ring = []
        for j in range(sides):
            a = 2.0 * math.pi * j / sides
            n = add(scale(side, math.cos(a)), scale(up, math.sin(a)))
            ring.append(mesh.vert(add(p, scale(n, radii[i])), (part, v), n, color))
        rings.append(ring)
    for i in range(count - 1):
        for j in range(sides):
            k = (j + 1) % sides
            mesh.quad(rings[i][j], rings[i][k], rings[i + 1][k], rings[i + 1][j])
    if cap:
        for end, ring, sign in ((path[-1], rings[-1], 1.0), (path[0], rings[0], -1.0)):
            tangent = norm(sub(path[-1], path[-2])) if sign > 0 else norm(sub(path[0], path[1]))
            mid = mesh.vert(end, (part, v_range[1] if sign > 0 else v_range[0]), tangent, color)
            for j in range(sides):
                k = (j + 1) % sides
                mesh.tri(mid, ring[j], ring[k])


def box(mesh, lo, hi, part, color=(0.0, 0.0, 0.0)):
    (x0, y0, z0), (x1, y1, z1) = lo, hi
    faces = [
        ((1, 0, 0), [(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)]),
        ((-1, 0, 0), [(x0, y0, z1), (x0, y1, z1), (x0, y1, z0), (x0, y0, z0)]),
        ((0, 1, 0), [(x0, y1, z0), (x0, y1, z1), (x1, y1, z1), (x1, y1, z0)]),
        ((0, -1, 0), [(x0, y0, z1), (x0, y0, z0), (x1, y0, z0), (x1, y0, z1)]),
        ((0, 0, 1), [(x1, y0, z1), (x1, y1, z1), (x0, y1, z1), (x0, y0, z1)]),
        ((0, 0, -1), [(x0, y0, z0), (x0, y1, z0), (x1, y1, z0), (x1, y0, z0)]),
    ]
    for n, quad in faces:
        ids = [mesh.vert(p, (part, (p[1] - y0) / max(y1 - y0, 1e-4)), n, color) for p in quad]
        mesh.quad(*ids)


def lathe(mesh, profile, sides, part, color=(0.0, 0.0, 0.0), center=(0.0, 0.0, 0.0)):
    """Revolve (radius, y) profile points around +Y. uv.y follows the profile."""
    rings = []
    count = len(profile)
    for i, (r, y) in enumerate(profile):
        r0, y0 = profile[max(i - 1, 0)]
        r1, y1 = profile[min(i + 1, count - 1)]
        dr, dy = r1 - r0, y1 - y0
        ring = []
        for j in range(sides + 1):
            a = 2.0 * math.pi * j / sides
            ca, sa = math.cos(a), math.sin(a)
            # Profile normal (dy, -dr) rotated around the axis.
            n = (dy * ca, -dr, dy * sa)
            p = (center[0] + r * ca, center[1] + y, center[2] + r * sa)
            ring.append(mesh.vert(p, (part, i / (count - 1)), n, color))
        rings.append(ring)
    for i in range(count - 1):
        for j in range(sides):
            mesh.quad(rings[i][j], rings[i + 1][j], rings[i + 1][j + 1], rings[i][j + 1])


def sheet(mesh, a, b, c, steps, part, color_fn):
    """Triangular sheet a(tack)-b(head)-c(clew) subdivided for cloth billow.

    color = color_fn(u, v) where u runs along the foot (a->c) and v up (->b).
    """
    n = norm(cross(sub(b, a), sub(c, a)))
    rows = []
    for i in range(steps + 1):
        v = i / steps
        row = []
        for j in range(steps - i + 1):
            u = j / steps
            # Barycentric: a*(1-u-v) + c*u + b*v
            p = tuple(a[k] * (1.0 - u - v) + c[k] * u + b[k] * v for k in range(3))
            row.append(mesh.vert(p, (0.0, v), n, color_fn(u, v)))
        rows.append(row)
    for i in range(steps):
        for j in range(steps - i):
            mesh.tri(rows[i][j], rows[i][j + 1], rows[i + 1][j])
            if j < steps - i - 1:
                mesh.tri(rows[i][j + 1], rows[i + 1][j + 1], rows[i + 1][j])
    # Stamp the part id into uv.x after the fact.
    first = rows[0][0]
    last = rows[-1][-1]
    for index in range(first - 1, last):
        mesh.vt[index] = (part, mesh.vt[index][1])


