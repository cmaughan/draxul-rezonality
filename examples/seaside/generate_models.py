def ocean_grid():
    mesh = Mesh("ocean_grid")
    rings, segments = 140, 220
    r0, r_max = 0.3, 1400.0
    k = math.log(r_max / r0) / (rings - 1)
    center = mesh.vert((0.0, 0.0, 0.0))
    ring_ids = []
    for i in range(rings):
        r = r0 * math.exp(k * i)
        ring = []
        for j in range(segments):
            a = 2.0 * math.pi * j / segments
            ring.append(mesh.vert((r * math.cos(a), 0.0, r * math.sin(a))))
        ring_ids.append(ring)
    for j in range(segments):
        jn = (j + 1) % segments
        mesh.tri(center, ring_ids[0][jn], ring_ids[0][j])
    for i in range(rings - 1):
        a, b = ring_ids[i], ring_ids[i + 1]
        for j in range(segments):
            jn = (j + 1) % segments
            mesh.quad(a[j], a[jn], b[jn], b[j])
    mesh.write("ocean_grid.obj", colors=False, normals=False, uvs=False)


